import math


def area(r):
    """
    Вычисляет площадь круга.

        Параметры:
            r (float): радиус круга.
        
        Возвращаемое значение:
            (float): площадь круга.
        
        Пример использования:
            >>> area(2)
            12.566370614359172
    """
    return math.pi * r * r


def perimeter(r):
    """
    Вычисляет длину окружности.

        Парамметры:
            r (float): радиус круга.
        
        Возвращаемое значение:
            (float): длина окружности.

        Пример использования:
            >>> perimeter(2)
            12.566370614359172
    """
    return 2 * math.pi * r

